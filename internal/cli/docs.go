package cli

// The `docs` verb: the command tree describes itself into files.
//
// intrastate's reference material — the flag grammar, the finding
// taxonomy, the refusal vocabulary, the exit contract — already lives in
// the binary, derived from the same constants the wire is emitted from
// (see help_all.go). Restating any of it in hand-written markdown
// creates a second description that rots the moment a code is renamed.
// So the markdown is GENERATED from the live command tree instead, and
// `make docs` plus a CI staleness gate keep the committed copy honest.
//
// Shape follows the prior art in the peer Go CLIs (helm's `helm docs`,
// goreleaser's `man`): a HIDDEN subcommand inside the shipped binary,
// rather than a separate `cmd/gen-docs` program. A second main package
// would have to reconstruct the command tree — and a generator that
// builds its own tree can silently describe a different CLI than the one
// that ships. Reaching cmd.Root() from inside the binary cannot.
//
// It is hidden because it addresses maintainers, not callers: it does
// not belong in the command list a user reads to learn the tool. It is
// still fully documented under `--help` for whoever runs it.
//
// One rule governs everything emitted here: NOTHING may vary between two
// builds of the same source. In particular the ldflags-stamped version
// never appears in generated output — it would dirty the committed files
// on every release build and turn the staleness gate into noise.

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/newcoinc/intrastate/internal/cli/clierr"
	"github.com/newcoinc/intrastate/internal/cli/respond"
	"github.com/spf13/cobra"
)

// generatedBanner marks every generated file. It carries the command
// that reproduces the file, so a reader who wants to change it is told
// what to run instead of editing a file their edit would not survive.
const generatedBanner = `<!-- AUTO-GENERATED by ` + "`make docs`" + `. DO NOT EDIT.
     The source is the command tree in internal/cli; edit the command's
     Long text or its withExtendedHelp body, then run ` + "`make docs`" + `. -->`

// docsPayload is the verb's success payload: the files written, relative
// to the output directory, in the order written.
type docsPayload struct {
	Dir   string   `json:"dir"`
	Files []string `json:"files"`
}

func newDocsCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:    "docs",
		Short:  "Generate the reference documentation from this command tree",
		Hidden: true,
		Long: `Generate the reference documentation from this command tree.

The command tree is the source of truth: this writes docs/cli-reference.md
and llms.txt from the same help bodies ` + "`--help-all`" + ` prints, so the
committed markdown cannot describe a CLI this binary does not implement.

Run it through ` + "`make docs`" + `; ` + "`make check`" + ` fails when the
committed copies are stale.`,
		SilenceErrors: true,
		SilenceUsage:  true,
		Args:          cobra.NoArgs,
		RunE:          runDocs,
	}
	cmd.Flags().String("dir", ".", "repository root to write the generated files under")
	withExtendedHelp(cmd, docsExtendedDesc)
	return cmd
}

const docsExtendedDesc = `Files written, both relative to --dir:

  docs/cli-reference.md   the full command reference — every command's
                          terse body, usage, flags, and extended help.
  llms.txt                the agent-oriented index, per the llms.txt
                          convention: what the tool is, the command
                          surface, and where the full reference lives.

Determinism is a contract, not a nicety. The staleness gate in
` + "`make check`" + ` regenerates these files and fails if the result
differs from what is committed, so anything that varies between two
builds of the same source would fail the build at random. That is why
the ldflags-stamped version appears in neither file.

To change what these files say, change what the COMMAND says — its Long
text, or its withExtendedHelp body — and regenerate. Editing the output
directly does not survive the next run.`

func runDocs(cmd *cobra.Command, _ []string) error {
	if ce := respond.ValidateMode(cmd); ce != nil {
		return respond.Fail(cmd, ce)
	}
	dir, _ := cmd.Flags().GetString("dir")
	root := cmd.Root()

	files := []struct {
		path   string
		render func(io.Writer, *cobra.Command)
	}{
		{filepath.Join("docs", "cli-reference.md"), writeCLIReference},
		{"llms.txt", writeLLMsTxt},
	}

	written := make([]string, 0, len(files))
	for _, f := range files {
		full := filepath.Join(dir, f.path)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return respond.Fail(cmd, &clierr.CLIError{
				Code:    "docs-write-failed",
				Param:   "dir",
				Message: "cannot create the directory for " + f.path,
				Detail:  err.Error(),
				Group:   clierr.GroupUserEnv,
				Cause:   err,
			})
		}
		var buf strings.Builder
		f.render(&buf, root)
		if err := os.WriteFile(full, []byte(buf.String()), 0o644); err != nil {
			return respond.Fail(cmd, &clierr.CLIError{
				Code:    "docs-write-failed",
				Param:   "dir",
				Message: "cannot write " + f.path,
				Detail:  err.Error(),
				Group:   clierr.GroupUserEnv,
				Cause:   err,
			})
		}
		written = append(written, f.path)
	}

	return respond.OK(cmd, respond.Success{
		Data: docsPayload{Dir: dir, Files: written},
	})
}

// writeCLIReference renders the whole tree: for each command, its terse
// body, its usage block, and its extended help. It is the file form of
// `intrastate --help-all`, and it is built by walking the SAME tree that
// command walks — there is no second description to keep in step.
func writeCLIReference(w io.Writer, root *cobra.Command) {
	fmt.Fprintln(w, generatedBanner)
	fmt.Fprintln(w)
	fmt.Fprintln(w, "# intrastate CLI reference")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "Every command, its flags, and its extended reference.")
	fmt.Fprintln(w, "The same content is available from the binary itself:")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "```sh")
	fmt.Fprintln(w, "intrastate --help-all           # this whole document")
	fmt.Fprintln(w, "intrastate <command> --help-all # one command's section")
	fmt.Fprintln(w, "```")

	walkCommandTree(root, func(c *cobra.Command) {
		if c.Hidden {
			return
		}
		fmt.Fprintln(w)
		fmt.Fprintf(w, "## %s\n", c.CommandPath())
		fmt.Fprintln(w)
		if c.Short != "" {
			fmt.Fprintln(w, c.Short)
			fmt.Fprintln(w)
		}
		if body := strings.TrimRight(c.Long, " \t\r\n"); body != "" && body != c.Short {
			fmt.Fprintln(w, "```")
			fmt.Fprintln(w, body)
			fmt.Fprintln(w, "```")
			fmt.Fprintln(w)
		}
		fmt.Fprintln(w, "```")
		fmt.Fprint(w, usageWithoutVersion(c))
		fmt.Fprintln(w, "```")
		if ext := extendedHelpFor(c); ext != "" {
			fmt.Fprintln(w)
			fmt.Fprintln(w, "```")
			fmt.Fprintln(w, ext)
			fmt.Fprintln(w, "```")
		}
	})
}

// writeLLMsTxt renders llms.txt per the convention: an H1, a blockquote
// summary, then annotated links. The command surface is enumerated from
// the live tree so a new verb appears here without anyone remembering to
// add it.
//
// It points an agent at the binary first. A file is a snapshot; the
// binary is the build actually installed, and `--help-all --as=json` is
// the machine-readable form of the same content.
func writeLLMsTxt(w io.Writer, root *cobra.Command) {
	fmt.Fprintln(w, "# intrastate")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "> A Go CLI that makes workflow state transitions explicit, reviewable,")
	fmt.Fprintln(w, "> and deterministic. A flow is authored once as a transition model — a")
	fmt.Fprintln(w, "> TOML document of tags, rules, guards, and writes — and callers")
	fmt.Fprintln(w, "> navigate it by asking the CLI rather than reimplementing the flow in")
	fmt.Fprintln(w, "> a skill, script, or agent. Given the same model, state, tags, and")
	fmt.Fprintln(w, "> recognized outcome, the answer is the same every time: one legal")
	fmt.Fprintln(w, "> plan, or one typed refusal.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "The binary is authoritative and self-describing. Prefer asking it over")
	fmt.Fprintln(w, "reading any file here — a file is a snapshot, the binary is the build")
	fmt.Fprintln(w, "you actually have:")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "```sh")
	fmt.Fprintln(w, "intrastate --help-all      # every command's full reference")
	fmt.Fprintln(w, "intrastate <cmd> --help-all")
	fmt.Fprintln(w, "intrastate <cmd> --as=json # one terminal JSON envelope per run")
	fmt.Fprintln(w, "```")
	fmt.Fprintln(w)

	fmt.Fprintln(w, "## Commands")
	fmt.Fprintln(w)
	walkCommandTree(root, func(c *cobra.Command) {
		if c.Hidden || c.Parent() == nil {
			return
		}
		fmt.Fprintf(w, "- `%s`: %s\n", c.CommandPath(), c.Short)
	})
	fmt.Fprintln(w)

	fmt.Fprintln(w, "## Docs")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "- [CLI reference](docs/cli-reference.md): every command, flag, and")
	fmt.Fprintln(w, "  extended body — generated from the command tree.")
	fmt.Fprintln(w, "- [Model authoring](docs/model-authoring.md): how to author a")
	fmt.Fprintln(w, "  transition model in TOML — the model class, a decision table's")
	fmt.Fprintln(w, "  cells, and the escape row. Not derivable from the CLI surface.")
	fmt.Fprintln(w, "- [Output contract](docs/cli-output-contract.md): worked JSON")
	fmt.Fprintln(w, "  payloads and the rationale behind the envelope shape.")
	fmt.Fprintln(w, "- [README](README.md): what it is, install, and a first invocation.")
	fmt.Fprintln(w)

	fmt.Fprintln(w, "## Optional")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "- [Decision records](docs/rdr/): the locked design decisions behind")
	fmt.Fprintln(w, "  the contracts above. History and rationale; the code is the source")
	fmt.Fprintln(w, "  of truth.")
	fmt.Fprintln(w, "- [CONTRIBUTING](CONTRIBUTING.md): layout, the contract every verb")
	fmt.Fprintln(w, "  follows, and the build targets.")
}

// usageWithoutVersion is cmd.UsageString with the ldflags-stamped
// `--version` line dropped.
//
// Cobra renders that flag's help as `version for intrastate` with no
// stamp in it, so today the string is already stable — but the stamp
// sits one template change away from the usage block, and a generated
// file that changes per build would fail the staleness gate on release
// builds only. Dropping the line keeps the gate honest by construction
// rather than by luck.
func usageWithoutVersion(c *cobra.Command) string {
	var kept []string
	for _, line := range strings.Split(c.UsageString(), "\n") {
		if strings.Contains(line, "--version") {
			continue
		}
		kept = append(kept, line)
	}
	return strings.Join(kept, "\n")
}
